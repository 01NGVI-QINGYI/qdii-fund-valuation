export const FUND_CATALOG = RAW.map(([short, aCode, cCode, fix], i) => ({
  index: i + 1,
  short,
  // name 只是占位，实际名称会在首次加载时由接口回填成官方全称
  classes: [
    { cls: 'A', code: aCode, name: short, fixed: fix?.fixed ? `A ${fix.fixed.split(' / ')[0]}` : null },
    cCode ? { cls: 'C', code: cCode, name: short, fixed: fix?.fixed?.includes('/') ? `C ${fix.fixed.split(' / ')[1]}` : (fix?.fixed?.startsWith('C') ? fix.fixed : null) } : null,
  ].filter(Boolean),
  note: fix?.why || null,
}));

/** 默认自选：每只基金取 A 类，保持"紧凑"。 */
export const DEFAULT_WATCH = FUND_CATALOG.map((f) => ({
  code: f.classes[0].code,
  name: f.classes[0].name,
}));

export const CATALOG_CODES = new Set(
  FUND_CATALOG.flatMap((f) => f.classes.map((c) => c.code)),
);

/** 代码被修正过的条目，用于在界面上给出提示。 */
